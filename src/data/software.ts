export function getSoftwareBySlug(slug: string): Software | undefined {
  return software.find((s) => s.slug === slug);
}

export function getSoftwareById(id: string): Software | undefined {
  return software.find((s) => s.id === id);
}

export function getSoftwareByCategory(categorySlug: string): Software[] {
  return software.filter((s) => s.categorySlugs.includes(categorySlug));
}

export function getFeaturedSoftware(): Software[] {
  return software.filter((s) => s.featured);
}

export function getTrendingSoftware(): Software[] {
  return software.filter((s) => s.trending);
}
